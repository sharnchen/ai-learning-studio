import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {learningProgress,progressSchema} from '../backend/learning-progress.mjs';
const db=new DatabaseSync(':memory:');db.exec(progressSchema);
const env={LEARNING_DB:{prepare(sql){return {bind(...params){return {async first(){return db.prepare(sql).get(...params)}}}}}}};
const reply=(body,status=200)=>({body,status});
const get=sub=>learningProgress(new Request('https://test/progress'),env,{sub},reply);
const put=(sub,revision,note)=>learningProgress(new Request('https://test/progress',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({accountId:'other',revision,state:{done:[1],known:[],notes:{1:note}}})}),env,{sub},reply);
assert.equal((await get('A')).body.state,null);
assert.equal((await put('A',0,'private A')).status,200);
assert.equal((await get('B')).body.state,null);
assert.equal((await put('B',0,'private B')).status,200);
assert.equal((await get('A')).body.state.notes[1],'private A');
assert.equal((await put('A',0,'overwrite')).status,409);
const writes=await Promise.all([put('A',1,'first'),put('A',1,'second')]);
assert.deepEqual(writes.map(x=>x.status).sort(),[200,409]);
assert.equal((await get('B')).body.state.notes[1],'private B');
assert.equal((await get('A')).body.revision,2);
assert.equal((await put('A',2,'x'.repeat(1048576))).status,413);
console.log('PASS account isolation, server-derived identity, atomic conflict detection, revision and size limits');
